"""Upright interface loads for every state of the duty spectrum, and the load cycles between them.

The fatigue check (scripts/fea/upright_fatigue.py) needs the upright's stress in each state the car
spends time in, not just the limit load cases. Each state of vehicle.json duty.spectrum (inside and
outside wheel for the cornering states) gets the same free-body split as the load cases
(upright_loads.split, static ride height, brakes on), in the upright's static frame.

Cycles (vehicle.json duty.cycle_model, assumed): corner events per km shared among the cornering
states by distance share, each a full outside <-> inside reversal (conservative); brake events per km
shared among the braking states, each against the 1 g static state; bump events against static.
Over the design life (season km x seasons).
Run: python duty_loads.py   Writes data/duty_loads.json and notes/duty_loads.md
"""
import json

import numpy as np

from bearings import state_loads
import stamps
from common import DATA, NOTES, load_hardpoints, load_vehicle, read_version
from forces import read_csv_rows
from suspension import make_corner
from upright_loads import split, to_static


@stamps.producer("duty_loads")
def main():
    hp, meta = load_hardpoints()
    veh = load_vehicle()
    corner = make_corner(hp, meta, veh["tyre"]["loaded_radius_mm"])
    members = read_csv_rows(DATA / "members.csv")
    derived = json.loads((DATA / "vehicle_derived.json").read_text())
    ver = read_version(DATA / "hardpoints.csv")
    duty = veh["duty"]
    pose = corner.pose(0.0)
    fwd = np.cross(hp["WA"] - hp["WC"], [0.0, 0.0, 1.0])
    fwd /= np.linalg.norm(fwd)
    states = {}
    for st in duty["spectrum"]:
        sides = (("out", True), ("in", False)) if st["ay_g"] else (("", True),)
        for tag, outside in sides:
            F = state_loads(veh, derived, st, outside)
            loads = [(np.array([F[0], 0.0, F[2]]), pose["cp"])]
            if F[1]:
                loads.append((np.array([0.0, F[1], 0.0]), pose["cp"] - fwd * veh["tyre"]["pneumatic_trail_mm_assumed"]))
            res = split(corner, pose, members, loads, veh, brakes_on=True)
            if res["resid"] > 1e-3:
                raise RuntimeError(f"{st['state']}: upright not in balance ({res['resid']:.2e})")
            name = st["state"] + (f", {'outside' if outside else 'inside'}" if tag else "")
            states[name] = {"tyre_N": np.round(F, 1).tolist(), **to_static(res)}
    # ---- cycles over the design life
    cm = duty["cycle_model"]["events_per_km_assumed"]
    km = duty["season_km_assumed"] * duty["life_target_seasons"]
    spec = duty["spectrum"]
    static = next(s["state"] for s in spec if not s["ay_g"] and not s["ax_g"] and s["bump_g"] == 1.0)
    corner_states = [s for s in spec if s["ay_g"]]
    brake_states = [s for s in spec if s["ax_g"] and not s["ay_g"]]
    bump_states = [s for s in spec if s["bump_g"] > 1.0]
    cycles = []
    for group, kind, events in ((corner_states, "corner", cm["corner"]), (brake_states, "brake", cm["brake"]),
                                (bump_states, "bump", cm["bump"])):
        total_share = sum(s["share"] for s in group)
        for s in group:
            n = events * km * s["share"] / total_share
            if kind == "corner":
                cycles.append({"a": f"{s['state']}, outside", "b": f"{s['state']}, inside", "n": n, "kind": kind})
            else:
                cycles.append({"a": s["state"], "b": static, "n": n, "kind": kind})
    out = {"_hardpoints": ver, "frame": "upright static frame (mm, N), as data/upright_loads.json",
           "life_km": km, "static_state": static, "states": states, "cycles": cycles,
           "basis": duty["cycle_model"]["basis"]}
    (DATA / "duty_loads.json").write_text(json.dumps(out, indent=1), encoding="utf-8")
    md = [f"# Duty-spectrum loads and cycles (hardpoints {ver})", "",
          "Generated by `scripts/duty_loads.py`. Do not edit by hand. Interface loads on the upright in each duty state "
          "(static ride height), and the load cycles over the design life "
          f"({duty['season_km_assumed']:.0f} km x {duty['life_target_seasons']:.0f} seasons, assumed).", "",
          "| State | Tyre Fx / Fy / Fz [N] | Upper BJ [N] | Lower BJ [N] | Row 1 / row 2 radial [N] |", "|---|---|---|---|---|"]
    for name, s in states.items():
        f = s["tyre_N"]
        md.append(f"| {name} | {f[0]:.0f} / {f[1]:.0f} / {f[2]:.0f} | {np.linalg.norm(s['UBJ']['force_N']):.0f} | "
                  f"{np.linalg.norm(s['LBJ']['force_N']):.0f} | {np.linalg.norm(s['row1']['force_N']):.0f} / "
                  f"{np.linalg.norm(s['row2']['force_N']):.0f} |")
    md += ["", "| Cycle | Between | Cycles over the life |", "|---|---|---|"]
    md += [f"| {c['kind']} | {c['a']} <-> {c['b']} | {c['n']:,.0f} |" for c in cycles]
    md += ["", f"Basis: {out['basis']}"]
    (NOTES / "duty_loads.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
