"""Mass budget from the CAD: designed parts from mesh volume x density, bought parts from
catalogue masses. Unsprung corner mass = everything that moves with the wheel plus half of
each link that spans wheel and chassis (requirement M-01: <= 11 kg).

Inputs: cad/meshes (scripts/fusion/job_export_meshes.py; refused if built from other inputs or another upright STEP,
or if a mesh file is not the one the index recorded), data/vehicle.json.
Run: python mass_budget.py   Writes data/mass_budget.csv and notes/mass_budget.md
"""
import csv

import stamps
from common import DATA, NOTES, cad_inputs_hash, load_mesh, load_mesh_index, load_vehicle, read_version

DENSITY = {"7075": 2810.0, "4130": 7850.0, "steel": 7850.0}  # kg/m3
# component (without side prefix) / body -> (material or None for catalogue, unsprung share)
RULES = {
    "Upright": ("7075", 1.0),
    "Hub, bearings, nut/hub": ("7075", 1.0),
    "Hub, bearings, nut/axle nut": ("steel", 1.0),
    "Hub, bearings, nut/inner bearing": (None, 1.0),
    "Hub, bearings, nut/outer bearing": (None, 1.0),
    "Brake disc": ("steel", 1.0),
    "Caliper (envelope)": (None, 1.0),
    "Wheel (Braid 10 in, envelope)": (None, 1.0),
    "Tyre (Hoosier 16x7.5-10, envelope)": (None, 1.0),
    "Upper wishbone": ("4130", 0.5),
    "Lower wishbone": ("4130", 0.5),
    "Tie rod": ("4130", 0.5),
    "Pushrod": ("4130", 0.5),
    "Rocker": ("7075", 0.0),
    "Damper body (Ohlins TTX25, envelope)": (None, 0.0),
    "Damper shaft": (None, 0.0),
    "ARB lever": ("steel", 0.0),
    "Drop link": ("steel", 0.0),
}
ALLOWANCES = [("Brake line, fluid, pads (allowance)", 0.15), ("Fasteners, spacers, circlips (allowance)", 0.20)]


def catalogue(veh):
    return {
        "Hub, bearings, nut/inner bearing": (veh["hub"]["mass_kg_each"], veh["hub"]["bearings"]),
        "Hub, bearings, nut/outer bearing": (veh["hub"]["mass_kg_each"], veh["hub"]["bearings"]),
        "Caliper (envelope)": (veh["brake"]["caliper"]["mass_kg"], veh["brake"]["caliper"]["model"]),
        "Wheel (Braid 10 in, envelope)": (veh["wheel"]["mass_kg"], veh["wheel"]["model"]),
        "Tyre (Hoosier 16x7.5-10, envelope)": (veh["tyre"]["mass_kg"], veh["tyre"]["model"]),
        "Damper body (Ohlins TTX25, envelope)": (veh["damper"]["mass_kg"] + 0.25, "TTX25 394 g + spring about 250 g"),
        "Damper shaft": (0.0, "included with the damper body"),
    }


@stamps.producer("mass_budget")
def main():
    veh = load_vehicle()
    cat = catalogue(veh)
    index = load_mesh_index()
    rows = []
    for fn, info in index.items():
        comp = info["component"]
        if not comp.startswith("L "):
            continue
        name = comp[2:]
        key = f"{name}/{info['body']}" if f"{name}/{info['body']}" in RULES else name
        if key not in RULES:
            continue
        mat, share = RULES[key]
        if mat is None:
            m, src = cat[key]
        else:
            vol = load_mesh(fn, info).volume * 1e-9  # mm3 -> m3
            m, src = vol * DENSITY[mat], f"CAD volume x {mat} ({DENSITY[mat]:.0f} kg/m3)"
        rows.append({"part": f"{name} / {info['body']}", "mass_kg": m, "unsprung_share": share, "basis": src})
    for n, m in ALLOWANCES:
        rows.append({"part": n, "mass_kg": m, "unsprung_share": 1.0, "basis": "allowance"})
    total_unsprung = sum(r["mass_kg"] * r["unsprung_share"] for r in rows)
    ver = read_version(DATA / "hardpoints.csv")
    with open(DATA / "mass_budget.csv", "w", newline="") as f:
        f.write(f"# hardpoints {ver}; cad {cad_inputs_hash()}; left front corner\n")
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        for r in rows:
            w.writerow({**r, "mass_kg": f"{r['mass_kg']:.3f}"})
    target = veh["unsprung_mass_front_corner_kg"]
    md = [f"# Mass budget, left front corner (hardpoints {ver})", "",
          "Generated by `scripts/mass_budget.py`. Designed parts: CAD volume x density; bought parts: catalogue; "
          "links that span wheel and chassis count half to the unsprung mass.", "",
          f"**Unsprung corner mass: {total_unsprung:.2f} kg (target <= {target:.0f} kg, M-01: "
          f"{'PASS' if total_unsprung <= target else 'FAIL'}).**", "",
          "| Part | Mass [kg] | Unsprung share | Basis |", "|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: -r["mass_kg"]):
        md.append(f"| {r['part']} | {r['mass_kg']:.3f} | {r['unsprung_share']:.1f} | {r['basis']} |")
    (NOTES / "mass_budget.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"unsprung corner mass {total_unsprung:.2f} kg (target {target} kg)")
    return total_unsprung


if __name__ == "__main__":
    main()
