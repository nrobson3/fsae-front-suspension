"""Benchmark the FEA chain against beam theory before it is used on a part (PLAN s10, D4).

Steel cantilever 200 x 20 x 20 mm, clamped at x = 0, 1000 N down on the free end.
  tip deflection = P L^3 / (3 E I) + P L / (k G A)   (Timoshenko shear term, k = 5/6)
  bending stress at mid-span, top fibre = M c / I with M = P L / 2
Mesh sizes 8 -> 2.5 mm show convergence. The clamp makes the root stress singular, so stress
is compared at mid-span, where beam theory is exact enough (Saint-Venant).
Run: python benchmark_cantilever.py   Writes data/fea_benchmark.csv and notes/fea_benchmark.md
"""
import csv
import sys

import numpy as np
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
from common import DATA, NOTES, ROOT  # noqa: E402
from fea import Model, load_mesh, mesh_box  # noqa: E402

L, B, H, P, E, NU = 200.0, 20.0, 20.0, 1000.0, 200e3, 0.3
SIZES = (8.0, 5.0, 3.5, 2.5)
TOL_PCT = 2.0     # acceptance: tip deflection and mid-span stress within 2 % of theory on the finest mesh


def theory():
    I = B * H ** 3 / 12
    G = E / (2 * (1 + NU))
    tip = P * L ** 3 / (3 * E * I) + P * L / (5 / 6 * G * B * H)
    sigma_mid = (P * L / 2) * (H / 2) / I
    return tip, sigma_mid


def run(size):
    work = ROOT / ".tmp" / "fea"
    work.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    m = Model(load_mesh(mesh_box(L, B, H, size, work / f"beam_{size}.msh")), E, NU)
    m.fix(lambda x: x[0] < 1e-6)
    m.traction(lambda x: x[0] > L - 1e-6, [0.0, 0.0, -P])
    m.solve()
    x = m.node_xyz()
    end = x[0] > L - 1e-6
    tip = -m.u[m.comp[2]][end].mean()                              # mean over the loaded end face
    top_mid = (np.abs(x[0] - L / 2) < 5.0) & (x[2] > H / 2 - 1e-6)  # symmetric window: linear M averages to M(L/2)
    sigma_mid = m.component(0, 0)[top_mid].mean()                  # hogging: top fibre in tension
    react = m.reactions()
    return {"size_mm": size, "dofs": m.K.shape[0], "tip_mm": tip, "sigma_mid_MPa": sigma_mid,
            "reaction_z_N": react[2], "seconds": time.time() - t0}


def main():
    tip_t, sig_t = theory()
    rows = [run(s) for s in SIZES]
    with open(DATA / "fea_benchmark.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        for r in rows:
            w.writerow({k: (f"{v:.5g}" if isinstance(v, float) else v) for k, v in r.items()})
    fin = rows[-1]
    e_tip, e_sig = (fin["tip_mm"] / tip_t - 1) * 100, (fin["sigma_mid_MPa"] / sig_t - 1) * 100
    ok = abs(e_tip) <= TOL_PCT and abs(e_sig) <= TOL_PCT
    md = ["# FEA benchmark: cantilever vs beam theory", "",
          "Generated by `scripts/fea/benchmark_cantilever.py`. Do not edit by hand.", "",
          f"Steel beam {L:.0f} x {B:.0f} x {H:.0f} mm, clamped at one end, {P:.0f} N on the free end. Quadratic "
          "tetrahedra (gmsh) solved with scikit-fem.", "",
          f"Theory: tip deflection {tip_t:.4f} mm (bending + shear), mid-span top-fibre stress {sig_t:.2f} MPa.", "",
          "| Max element size [mm] | DOFs | Tip deflection [mm] | Error | Mid-span stress [MPa] | Error | Reaction [N] | Time [s] |",
          "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| {r['size_mm']:.1f} | {r['dofs']} | {r['tip_mm']:.4f} | {(r['tip_mm'] / tip_t - 1) * 100:+.2f} % | "
                  f"{r['sigma_mid_MPa']:.2f} | {(r['sigma_mid_MPa'] / sig_t - 1) * 100:+.2f} % | {r['reaction_z_N']:.1f} | "
                  f"{r['seconds']:.1f} |")
    md += ["", f"**Result: {'PASS' if ok else 'FAIL'}** (finest mesh within {TOL_PCT:.0f} % of theory on both: "
           f"{e_tip:+.2f} % deflection, {e_sig:+.2f} % stress). The reaction balances the load."]
    (NOTES / "fea_benchmark.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))
    return ok


if __name__ == "__main__":
    sys.exit(0 if main() else 1)
