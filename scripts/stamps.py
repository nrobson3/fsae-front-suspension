"""What each generated output was made from. data/stamps.json holds one stamp per producer (a script that run_all
runs): the content hash of every input it read (its data files and the project code it runs) and of every output
it wrote. stale() says why an output is not current, following generated inputs back to the producers that made
them, and requirements_matrix.load_sources refuses to build the matrix while it reports anything.

A producer's entry point is wrapped in @stamps.producer(name); its data inputs and outputs are declared in
PRODUCERS, and its code is found from its import statements. The wrapper:
  - hashes the inputs before the run, so an input edited during the run leaves the outputs stale;
  - records every project file the run opens or moves into place (a Python audit hook) and fails a run that read
    a file its stamp would not cover: an undeclared data file, code it does not import, a mesh the index does not
    list, or its own previous output. So the declarations cannot fall behind the code;
  - writes the stamp only when the run rewrote every declared output. A run with trial inputs, or one that wrote
    nothing, leaves the old stamp, which then no longer matches.
Reads that do not go through Python's open (gmsh reading a STEP) cannot be traced, so they are declared by hand.

The upright STEP is stamped another way. scripts/upright/upright_geom.py is a CAD input (fingerprint.CODE_FILES), and
editing it to stamp itself would make every committed CAD mesh stale until Fusion rebuilt them. verify_upright()
instead regenerates the upright in a scratch folder holding only its declared inputs, and stamps the committed files
only if they are reproduced exactly (the STEPs' DATA sections; their headers carry a timestamp). run_all does it
first: under a minute, and only when an input or the STEP changed since the last check.

Standard library only.
"""
