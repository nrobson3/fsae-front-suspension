# ---------------------------------------------------------------- hashing
MISSING, UNREADABLE = "missing", "unreadable"      # never equal to a hash, and a missing input is never current


def content_sha(path):
    """A file's content hash: line endings ignored for text, a STEP file from its DATA section (UNREADABLE if it
    has none, so a broken STEP reads as changed)."""
    path = Path(path)
    raw = path.read_bytes()
    if path.suffix.lower() in BINARY:
        return fingerprint.sha16(raw)
    if path.suffix.lower() in (".step", ".stp"):
        try:
            return fingerprint.sha16(fingerprint.step_data(raw))
        except ValueError:
            return UNREADABLE
    return fingerprint.sha16(raw.replace(b"\r\n", b"\n"))


def _module_file(name, bases):
    """The file a dotted module name resolves to in the first of these folders that has it (a module, or a
    package's __init__.py), or None."""
    for base in bases:
        stem = Path(base).joinpath(*name.split("."))
        for cand in (stem.with_name(stem.name + ".py"), stem / "__init__.py"):
            if cand.is_file():
                return cand
    return None


def code_files(script, root=None):
    """The project code a script runs: itself and every module under scripts/ that it imports, directly or through
    another module, read from the import statements (so a new import is picked up by itself): `import a.b` (and the
    package a), `from a import b` (b may be a module), and relative imports. Imports built at run time (importlib)
    are not seen; none of the producers uses them."""
    root = Path(root or ROOT)
    found, todo = set(), [root / script]
    while todo:
        path = todo.pop()
        rel = path.relative_to(root).as_posix()
        if rel in found:
            continue
        found.add(rel)
        for node in ast.walk(ast.parse(path.read_bytes(), filename=str(path))):
            if isinstance(node, ast.Import):
                bases, names = (path.parent, root / "scripts"), [a.name for a in node.names]
            elif isinstance(node, ast.ImportFrom):
                if node.level:                                   # relative: from the importing file's package
                    base = path.parent
                    for _ in range(node.level - 1):
                        base = base.parent
                    bases = (base,)
                else:
                    bases = (path.parent, root / "scripts")      # the script's own folder first, as Python does
                mod = node.module or ""
                names = ([mod] if mod else []) + [f"{mod}.{a.name}" if mod else a.name for a in node.names
                                                  if a.name != "*"]
            else:
                continue
            for name in names:
                parts = name.split(".")
                for i in range(1, len(parts) + 1):               # the packages on the way, then the module
                    f = _module_file(".".join(parts[:i]), bases)
                    if f is not None and f.name not in NOT_CODE and _inside(f, root):
                        todo.append(f)
    return sorted(found)


def _inside(path, root):
    try:
        Path(path).relative_to(root)
        return True
    except ValueError:
        return False


def input_hashes(name, root=None):
    """{path: content hash} of a producer's declared data inputs and its code (MISSING for a missing file)."""
    root = Path(root or ROOT)
    script, data, _ = PRODUCERS[name]
    with _untraced():
        rels = sorted(set(data) | set(code_files(script, root)))
        return {rel: content_sha(root / rel) if (root / rel).exists() else MISSING for rel in rels}


def _load(root):
    path = Path(root) / STAMPS
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def _record(name, inputs, root=None, outputs=None):
    """Write the producer's stamp: the input hashes taken before its run, and its outputs' hashes (now, unless the
    caller passes the ones it compared). Written to a temporary file and moved into place, retried while Windows
    (OneDrive, a virus scanner) holds the file."""
    root = Path(root or ROOT)
    with _untraced():
        if outputs is None:
            outputs = {rel: content_sha(root / rel) if (root / rel).exists() else MISSING for rel in PRODUCERS[name][2]}
        bad = [rel for rel, h in {**inputs, **outputs}.items() if h in (MISSING, UNREADABLE)]
        if bad:
            raise RuntimeError(f"{name}: {bad} are missing or unreadable, so its outputs are not stamped")
        try:
            st = _load(root)
        except ValueError:
            st = {}                               # a damaged stamp file: start again (every other stamp is lost: stale)
        st["_about"] = ABOUT
        st[name] = {"inputs": inputs, "outputs": outputs}
        dest = root / STAMPS
        fd, tmp = tempfile.mkstemp(prefix="stamps.", suffix=".tmp", dir=str(dest.parent))
        try:
            with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
                f.write(json.dumps(st, indent=1, sort_keys=True) + "\n")
                f.flush()
                os.fsync(f.fileno())
            for attempt in range(20):
                try:
                    os.replace(tmp, dest)
                    break
                except PermissionError:
                    if attempt == 19:
                        raise
                    time.sleep(0.25)
        finally:
            try:
                if os.path.exists(tmp):
                    os.remove(tmp)
            except OSError:
                pass                              # a leftover temporary file must not hide the real error


# ---------------------------------------------------------------- checking
def stale(names=None, root=None, follow=True):
    """Why outputs are not current: [] when every listed producer (default: all of them) has a stamp, its inputs and
    code have the content they had when it ran, its outputs are what it wrote, and (follow) every generated input it
    read is current in the same way."""
    root = Path(root or ROOT)
    with _untraced():
        try:
            st = _load(root)
        except ValueError as e:
            return [f"{STAMPS} is not valid JSON ({e}): run scripts/run_all.py"]
        except OSError as e:                      # held by another program (OneDrive, a virus scanner): not current
            return [f"{STAMPS} cannot be read ({e}): try again"]
        made_by = {out: n for n, (_, _, outs) in PRODUCERS.items() for out in outs}
        why, done = [], set()
        todo = list(PRODUCERS if names is None else names)
        while todo:
            name = todo.pop(0)
            if name in done:
                continue
            done.add(name)
            _, data, outputs = PRODUCERS[name]
            try:
                why += _stale_one(name, st.get(name), root)
            except (OSError, SyntaxError, ValueError, KeyError, TypeError, AttributeError) as e:
                why.append(f"{name}: its stamp cannot be checked ({type(e).__name__}: {e})")
            if follow:
                todo += [made_by[rel] for rel in data if rel in made_by and made_by[rel] != name]
        return why


def _stale_one(name, s, root):
    _, _, outputs = PRODUCERS[name]
    hint = HINT.get(name, "run scripts/run_all.py")
    if not s:
        return [f"{name} has no stamp ({hint})"]
    why = []
    now = input_hashes(name, root)
    bad = [rel for rel, h in now.items() if h in (MISSING, UNREADABLE)]
    if bad:                                       # never current, whatever the stamp holds
        why.append(f"{name}: its inputs {bad} are missing or unreadable ({hint})")
    if set(now) != set(s["inputs"]):
        gone, new = sorted(set(s["inputs"]) - set(now)), sorted(set(now) - set(s["inputs"]))
        why.append(f"{name}'s inputs are not the ones it was stamped with (now also {new}, no longer {gone}; {hint})")
    else:
        changed = [rel for rel in now if now[rel] != s["inputs"][rel]]
        if changed:
            why.append(f"{name}: {', '.join(changed)} changed since it ran ({hint})")
    if set(outputs) != set(s["outputs"]):
        why.append(f"{name}'s outputs are not the ones it was stamped with ({hint})")
    for rel in outputs:
        have = content_sha(root / rel) if (root / rel).exists() else MISSING
        if have in (MISSING, UNREADABLE):
            why.append(f"{rel} is {'missing' if have == MISSING else 'unreadable'} ({hint})")
        elif have != s["outputs"].get(rel):
            why.append(f"{rel} is not what {name} wrote: edited or replaced since ({hint})")
    return why


# ---------------------------------------------------------------- tracing a producer's run
_RUNS = []                  # the stamped runs in progress; each records the project files it opens
_LOCAL = threading.local()  # per thread: above 0 while this module reads files itself, or inside the hook
_HOOKED = []


@contextlib.contextmanager
def _untraced():
    _LOCAL.depth = getattr(_LOCAL, "depth", 0) + 1
    try:
        yield
    finally:
        _LOCAL.depth -= 1


def _key(rel):
    return os.path.normcase(rel).replace("\\", "/")


def _norm(path):
    return os.path.normcase(os.path.abspath(os.fsdecode(path)))


def _note(path, read, write):
    p = _norm(path)
    for run in _RUNS:
        hit = p.startswith(run["root"])
        if not hit:                                # another spelling of the same place (a junction, subst, link)
            p = os.path.normcase(os.path.realpath(p))
            hit = p.startswith(run["root"])
        if hit:
            rel = p[len(run["root"]):].replace("\\", "/")
            if read:
                run["reads"].add(rel)
            if write:
                run["writes"].add(rel)
            run["first"].setdefault(rel, "r" if read else "w")


def _audit(event, args):
    # os.replace raises the os.rename event in CPython; both names are listed
    if not _RUNS or event not in ("open", "os.rename", "os.replace") or getattr(_LOCAL, "depth", 0):
        return
    _LOCAL.depth = 1                                # realpath must not re-enter the hook
    try:
        if event == "open":
            path, mode, flags = args
            if isinstance(path, (str, bytes, os.PathLike)):
                # what a mode keeps of the file's old content is read: 'r', 'r+', 'a' (an append builds on it);
                # 'w', 'w+' and 'x' start empty
                if isinstance(mode, str):
                    write = any(c in mode for c in "wax+")
                    read = "r" in mode or "a" in mode
                else:
                    f = flags or 0
                    write = bool(f & (os.O_WRONLY | os.O_RDWR | os.O_APPEND | os.O_CREAT))
                    read = not (f & os.O_WRONLY) and not (f & os.O_TRUNC) or bool(f & os.O_APPEND)
                _note(path, read, write)
        elif isinstance(args[1], (str, bytes, os.PathLike)):     # a file moved into place is a write of its target
            _note(args[1], False, True)
    except Exception:                               # never break the call it watches; but the trace is now partial,
        try:                                        # so the run must not be stamped
            for run in _RUNS:
                run["failed"] = True
        except Exception:
            pass
    finally:
        _LOCAL.depth = 0


def _source_of(rel):
    """The module source a read stands for: x.py itself, or x.py for its compiled __pycache__/x.cpython-NN.pyc."""
    head, _, tail = rel.rpartition("/")
    if tail.endswith(".pyc") and head.rpartition("/")[2] == "__pycache__":
        return f"{head.rpartition('/')[0]}/{tail.split('.')[0]}.py".lstrip("/")
    return rel


def _undeclared(name, seen, root):
    """The files a run read that its producer does not declare. Code counts as covered only if the stamp hashes it:
    the modules it imports (code_files), the stamping machinery, and for a producer that reads the meshes the CAD code
    the mesh index pins (load_mesh_index checks the CAD fingerprint). A mesh file is covered by a declared mesh index
    only if the index lists it. An output may be read only after the run wrote it (reading the previous output would
    make it an input the stamp does not hold)."""
    script, data, outputs = PRODUCERS[name]
    allowed = {_key(p) for p in data} | {_key(p) for p in outputs if seen["first"].get(_key(p)) == "w"}
    code = set(code_files(script, root)) | {f"scripts/{m}" for m in NOT_CODE}
    meshes = set()
    if _key(MESH_INDEX) in allowed and (Path(root) / MESH_INDEX).exists():
        code |= set(fingerprint.CODE_FILES)
        with _untraced():
            meshes = {_key(f"cad/meshes/{fn}") for fn in json.loads((Path(root) / MESH_INDEX).read_text(encoding="utf-8"))
                      if not fn.startswith("_")}
    code = {_key(c) for c in code}
    return [r for r in sorted(seen["reads"]) if r not in allowed and r not in meshes and _source_of(r) not in code]


def producer(name, when=None):
    """Wrap a producer's entry point (see the module docstring). `when`, called with the same arguments, says whether
    the call is the design's own run: a call with trial inputs (False) runs unstamped."""
    if name not in PRODUCERS:
        raise KeyError(f"{name} is not in stamps.PRODUCERS")

    def deco(fn):
        @functools.wraps(fn)
        def run(*args, **kwargs):
            if when is not None and not when(*args, **kwargs):
                return fn(*args, **kwargs)
            root = Path(ROOT)
            before = input_hashes(name, root)
            if not _HOOKED:
                sys.addaudithook(_audit)
                _HOOKED.append(True)
            seen = {"root": os.path.normcase(os.path.realpath(str(root))) + os.sep, "reads": set(), "writes": set(),
                    "first": {}, "failed": False}
            _RUNS.append(seen)
            try:
                result = fn(*args, **kwargs)
            finally:
                _RUNS[:] = [r for r in _RUNS if r is not seen]      # by identity: a nested run's record may be equal
            if seen["failed"]:
                raise RuntimeError(f"{name}: the trace of the files it opened failed during the run, so its outputs "
                                   "are not stamped: run it again")
            if not all(_key(o) in seen["writes"] for o in PRODUCERS[name][2]):
                return result                 # not every output rewritten: no new stamp (the old one no longer matches)
            extra = _undeclared(name, seen, root)
            if extra:
                raise RuntimeError(f"{name} read {extra}, which stamps.PRODUCERS['{name}'] does not declare: declare "
                                   "them, so its stamp covers them (its outputs are not stamped until then)")
            _record(name, before, root)
            return result
        return run
    return deco


# ---------------------------------------------------------------- the upright STEP
def _regenerate_upright(folder):
    """Run upright_geom.py in the scratch folder. PYTHONPATH is dropped so it cannot import a module from the real
    tree that the folder lacks, and its output is read as UTF-8 whatever the console's code page."""
    env = {k: v for k, v in os.environ.items() if k.upper() not in ("PYTHONPATH", "PYTHONIOENCODING")}
    env["PYTHONUTF8"] = "1"
    env["PYTHONIOENCODING"] = "utf-8"
    res = subprocess.run([sys.executable, str(Path(folder) / PRODUCERS["upright_geom"][0])], cwd=str(folder), env=env,
                         capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=1800)
    if res.returncode:
        raise RuntimeError("regenerating the upright in a scratch copy of its inputs failed (an input it reads may be "
                           "missing from stamps.PRODUCERS['upright_geom']):\n" + (res.stderr or res.stdout)[-2000:])


def verify_upright(regenerate=_regenerate_upright, root=None):
    """Stamp the committed upright files if, and only if, regenerating them from today's inputs reproduces them.
    -> [] if the stamp was already current, else what had changed (the stamp is then renewed); raises if the
    committed files are not reproduced."""
    root = Path(root or ROOT)
    why = stale(["upright_geom"], root=root)
    if not why:
        return []
    before = input_hashes("upright_geom", root)
    missing = [rel for rel, h in before.items() if h in (MISSING, UNREADABLE)]
    if missing:
        raise RuntimeError(f"the upright's inputs are missing or unreadable: {missing}")
    outputs = PRODUCERS["upright_geom"][2]
    with tempfile.TemporaryDirectory(prefix="upright_check_", ignore_cleanup_errors=True) as tmp:
        tmp = Path(tmp)
        # the declared inputs, the stamping machinery (not an input, but importable), and the output folders
        for rel in list(before) + [f"scripts/{m}" for m in NOT_CODE if (root / "scripts" / m).exists()]:
            (tmp / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(root / rel, tmp / rel)
        for rel in outputs:
            (tmp / rel).parent.mkdir(parents=True, exist_ok=True)
        regenerate(tmp)
        made = {rel: content_sha(tmp / rel) if (tmp / rel).exists() else MISSING for rel in outputs}
    have = {rel: content_sha(root / rel) if (root / rel).exists() else MISSING for rel in outputs}
    differ = [rel for rel in outputs if made[rel] != have[rel] or have[rel] in (MISSING, UNREADABLE)]
    if differ:
        raise RuntimeError(f"the committed upright is not what scripts/upright/upright_geom.py gives from today's inputs "
                           f"({', '.join(differ)} differ; {'; '.join(why)}): regenerate it, rebuild the CAD "
                           "(scripts/fusion/job_build.py) and re-export the meshes (job_export_meshes.py)")
    if input_hashes("upright_geom", root) != before:
        raise RuntimeError("the upright's inputs changed while it was being checked: run the check again")
    _record("upright_geom", before, root, outputs=have)    # the hashes compared: a later edit reads as stale
    return why


if __name__ == "__main__":
    left = stale()
    print("\n".join(left) if left else f"every output in {STAMPS} is current")
    sys.exit(1 if left else 0)
