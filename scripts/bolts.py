"""Bending of the pins (bolts) through the upright's clevises and the pushrod bracket.

A bolt through a double-shear clevis carrying a ball or rod end in the middle bends. The standard
lug-pin model (Melcon & Hoblit; Bruhn D1.6) gives the moment
    M = (P / 2) (t_ear / 2 + g + t_inner / 4)
with g the gap between the ear and the inner part (filled by the misalignment spacers). Elastic
stress M / (pi d^3 / 32) plus the preload tension F / (pi d^2 / 4), F = T / (K d) from the specified
torque (data/upright_design.json bolt_torque), is checked against the bolt's yield with FoS >= 1.5
(conservative: the two added at the same fibre, no plastic shape factor, no credit for clamp friction). The load is the largest force component
normal to the bolt over every load case (data/upright_loads.json for the upright joints,
data/member_forces.csv for the pushrod).
Run: python bolts.py   Writes data/bolt_checks.csv and notes/bolts.md
"""
import csv
import json
import math

import numpy as np

import stamps
from common import DATA, NOTES, load_hardpoints, read_version, unit

FOS = 1.5


def node_height(members, member):
    od = float(next(m for m in members if m["member"] == member)["tube_od_mm"])
    return od + 6.0                      # the legs weld inside the node (fsae_parts.BJ_HOUSING_H)


@stamps.producer("bolts")
def main():
    hp, _ = load_hardpoints()
    ver = read_version(DATA / "hardpoints.csv")
    ud = json.loads((DATA / "upright_design.json").read_text())
    upl = json.loads((DATA / "upright_loads.json").read_text())
    with open(DATA / "members.csv", newline="") as f:
        members = list(csv.DictReader(l for l in f if not l.startswith("#")))
    with open(DATA / "member_forces.csv", newline="") as f:
        mf = list(csv.DictReader(l for l in f if not l.startswith("#")))
    k = unit(hp["UCA_O"] - hp["LCA_O"])
    ear, spacer = ud["clevis"]["ear_t_mm"], ud["clevis"]["spacer_mm"]

    def worst(key, axis):
        best = (0.0, "")
        for lcid, c in upl["cases"].items():
            F = np.array(c[key]["force_N"])
            fn = np.linalg.norm(F - axis * np.dot(F, axis))
            best = max(best, (fn, lcid))
        return best

    tie = unit(hp["TR_O"] - hp["TR_I"])
    b_tie = unit(np.cross(np.cross(tie, k), tie))     # bolt normal to the tie rod, as close to the kingpin as possible
    bj = ud["ball_joints"]
    joints = []
    for name, key, member, part in (("Upper ball joint", "UBJ", "UCA front leg", bj["upper"]),
                                    ("Lower ball joint", "LBJ", "LCA front leg", bj["lower"])):
        P, lc = worst(key, k)
        joints.append({"joint": name, "key": key, "bolt": part["bolt"], "d": part["bolt_d_mm"], "Fty": part["bolt_Fty_MPa"],
                       "t_ear": ear, "t_in": part["ball_w_in"] * 25.4,
                       "span": node_height(members, member) + 2 * spacer, "P": P, "lc": lc})
    P, lc = worst("TR", b_tie)
    sa = ud["steering_arm"]
    joints.append({"joint": "Tie rod outer rod end", "key": "TR", "bolt": sa["bolt"], "d": sa["bolt_d_mm"], "Fty": sa["bolt_Fty_MPa"],
                   "t_ear": ear, "t_in": sa["rod_end_w_mm"], "span": sa["rod_end_w_mm"] + 2 * spacer, "P": P, "lc": lc})
    push = max((r for r in mf if r["Pushrod"]), key=lambda r: abs(float(r["Pushrod"])))   # LC6 rows list the tie rod only
    tab = float(next(m for m in members if m["member"] == "Pushrod")["tab_t_mm"])
    joints.append({"joint": "Pushrod lower rod end (LCA bracket)", "key": "push", "bolt": "M8 10.9", "d": 8.0, "Fty": 940.0,
                   "t_ear": tab, "t_in": 12.0, "span": 12.0 + 2 * spacer, "P": abs(float(push["Pushrod"])), "lc": push["lc"]})
    torque = ud["bolt_torque"]
    rows = []
    for j in joints:
        g = (j["span"] - j["t_in"]) / 2
        arm = j["t_ear"] / 2 + g + j["t_in"] / 4
        M = j["P"] / 2 * arm
        sigma = M / (math.pi * j["d"] ** 3 / 32)
        F0 = torque[j["key"]]["torque_Nm"] * 1000 / (torque["K_nut_factor"] * j["d"])
        sig_t = F0 / (math.pi * j["d"] ** 2 / 4)
        rows.append({**j, "gap": g, "arm": arm, "M_Nm": M / 1000, "sigma": sigma, "fos": j["Fty"] / sigma,
                     "F0": F0, "sig_t": sig_t, "fos_c": j["Fty"] / (sigma + sig_t)})
    with open(DATA / "bolt_checks.csv", "w", newline="") as f:
        f.write(f"# hardpoints {ver}\n")
        w = csv.writer(f)
        w.writerow(["joint", "bolt", "load_N", "critical_lc", "arm_mm", "moment_Nm", "bending_MPa", "fos_bending",
                    "preload_N", "tension_MPa", "fos_combined"])
        for r in rows:
            w.writerow([r["joint"], r["bolt"], f"{r['P']:.0f}", r["lc"], f"{r['arm']:.1f}", f"{r['M_Nm']:.2f}",
                        f"{r['sigma']:.0f}", f"{r['fos']:.2f}", f"{r['F0']:.0f}", f"{r['sig_t']:.0f}", f"{r['fos_c']:.2f}"])
    md = [f"# Clevis bolt bending (hardpoints {ver})", "", "Generated by `scripts/bolts.py`. Do not edit by hand.", "",
          "M = (P/2)(t_ear/2 + gap + t_inner/4) (lug-pin model); bending stress plus the preload tension F = T / (K d) "
          f"(K = {torque['K_nut_factor']}) at the specified torque, against the bolt's yield, FoS >= 1.5.", "",
          "| Joint | Bolt | Load normal to the bolt [N] | Case | Ear / gap / inner [mm] | Arm [mm] | M [N m] | Bending [MPa] "
          "| Torque [N m] / preload [kN] | Tension [MPa] | FoS (bending + tension) |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| {r['joint']} | {r['bolt']} | {r['P']:.0f} | {r['lc']} | {r['t_ear']:g} / {r['gap']:.1f} / "
                  f"{r['t_in']:.1f} | {r['arm']:.1f} | {r['M_Nm']:.1f} | {r['sigma']:.0f} | "
                  f"{torque[r['key']]['torque_Nm']:g} / {r['F0'] / 1000:.1f} | {r['sig_t']:.0f} | "
                  f"{r['fos_c']:.2f} {'PASS' if r['fos_c'] >= FOS else 'FAIL'} |")
    md += ["", ud["ball_joints"]["why_lower_com6"]]
    (NOTES / "bolts.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
